"""Build and save the fixed held-out test set for the ablation study.

Must be run ONCE before any training.  Reads the full 120-trajectory training
dataset, reserves 20 trajectories as a permanent test set, and writes:

    ablation_data_study/data/plecs_test_fixed.npz   — 20 held-out trajectories
    ablation_data_study/data/test_indices.json       — original dataset indices

The remaining 100 trajectories become the training pool for all ablation
training scripts; they never touch the 20 test trajectories.

Regime convention (synchronous buck, no freewheeling diode):
  - Unidirectional: i_L >= 0 — standard forward conduction.
  - Bidirectional:  i_L < BIDIR_I_THRESHOLD — reverse current through the
                    synchronous MOSFET (what a freewheeling-diode converter
                    would clamp to classical DCM; here the current goes negative).

Run from bidir_buck_model/:
    python ablation_data_study/build_fixed_test_set.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent   # bidir_buck_model/
ABLATION_DIR = Path(__file__).resolve().parent  # ablation_data_study/

sys.path.insert(0, str(ROOT / "src"))

from generate_dataset import load_dataset, save_dataset  # noqa: E402

# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

# Full training dataset (120 trajectories generated by PLECS).
# Note: the task description refers to this as plecs_dcm_train1.npz; the
# actual file produced by generate_plecs_bidir_dataset.py is plecs_bidir_train2.npz.
DATA_PATH = ROOT / "data" / "plecs_bidir_train2.npz"

TEST_SET_PATH = ABLATION_DIR / "data" / "plecs_test_fixed.npz"
TEST_IDX_PATH = ABLATION_DIR / "data" / "test_indices.json"

N_TEST = 20
TEST_SEED = 999  # Separate seed — never reused for training

# A trajectory is bidirectional-dominant when more than this fraction of its
# samples have i_L below BIDIR_I_THRESHOLD.
BIDIR_I_THRESHOLD = -0.05   # A
BIDIR_DOMINANT_FRAC = 0.05  # 5 %


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    if not DATA_PATH.exists():
        raise FileNotFoundError(
            f"Training dataset not found: {DATA_PATH}\n"
            "Generate it first:\n"
            "  python src/generate_plecs_bidir_dataset.py"
        )

    print(f"Loading dataset : {DATA_PATH}")
    all_trajs = load_dataset(DATA_PATH)
    n_total = len(all_trajs)
    print(f"Total trajectories : {n_total}")

    if N_TEST >= n_total:
        raise ValueError(
            f"Requested {N_TEST} test trajectories but dataset only has {n_total}."
        )

    # ---- Select test indices with a dedicated seed ----
    rng = np.random.default_rng(TEST_SEED)
    perm = rng.permutation(n_total)
    test_indices: list[int] = sorted(int(i) for i in perm[:N_TEST])
    test_set_indices = set(test_indices)
    train_pool_indices: list[int] = [
        i for i in range(n_total) if i not in test_set_indices
    ]

    print(f"\nTest seed        : {TEST_SEED}")
    print(f"Test indices     : {test_indices}")
    print(f"Training pool    : {len(train_pool_indices)} trajectories "
          f"(indices not in test set)")

    # ---- Regime statistics for the test set ----
    test_trajs = [all_trajs[i] for i in test_indices]
    n_bidir_dom = 0
    n_unidir_dom = 0
    for td in test_trajs:
        iL = np.asarray(td["i_L"], dtype=np.float32)
        frac_bidir = float(np.mean(iL < BIDIR_I_THRESHOLD))
        if frac_bidir > BIDIR_DOMINANT_FRAC:
            n_bidir_dom += 1
        else:
            n_unidir_dom += 1

    print(f"\nTest set regime composition")
    print(f"  (bidirectional-dominant = i_L < {BIDIR_I_THRESHOLD} A "
          f"in > {BIDIR_DOMINANT_FRAC * 100:.0f}% of samples)")
    print(f"  Bidirectional-dominant : {n_bidir_dom} / {N_TEST}")
    print(f"  Unidirectional-dominant: {n_unidir_dom} / {N_TEST}")

    # ---- Save test set ----
    TEST_SET_PATH.parent.mkdir(parents=True, exist_ok=True)
    save_dataset(test_trajs, TEST_SET_PATH)
    print(f"\nSaved test set     : {TEST_SET_PATH}")

    # ---- Save index metadata ----
    idx_data = {
        "test_indices": test_indices,
        "train_pool_indices": train_pool_indices,
        "test_seed": TEST_SEED,
        "n_test": N_TEST,
        "n_total": n_total,
        "n_train_pool": len(train_pool_indices),
        "source_dataset": DATA_PATH.name,
        "bidir_dominant_in_test": n_bidir_dom,
        "unidir_dominant_in_test": n_unidir_dom,
    }
    with open(TEST_IDX_PATH, "w") as f:
        json.dump(idx_data, f, indent=2)
    print(f"Saved test indices : {TEST_IDX_PATH}")

    print(f"\nDone.  {len(train_pool_indices)} trajectories are available "
          f"for training (train_pool_indices in test_indices.json).")
    print("Run training scripts next — they will exclude the test set automatically.")


if __name__ == "__main__":
    main()
